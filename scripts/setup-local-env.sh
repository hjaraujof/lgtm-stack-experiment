#!/bin/bash
# Fetches secrets from AWS Secrets Manager and creates .env file for local development
# Run this script before `docker compose up` to enable grafana-init container

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
ENV_FILE="${PROJECT_ROOT}/.env"
SECRET_PATH="/example/dev/lgtm-stack"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log_info() {
    echo -e "${GREEN}[INFO]${NC} $1"
}

log_warn() {
    echo -e "${YELLOW}[WARN]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

log_info "Fetching secrets from AWS Secrets Manager: ${SECRET_PATH}"

# Fetch secrets
SECRETS_JSON=$(aws secretsmanager get-secret-value \
    --secret-id "${SECRET_PATH}" \
    --query 'SecretString' \
    --output text 2>/dev/null) || {
    log_error "Failed to fetch secrets from AWS Secrets Manager"
    log_error "Make sure you have valid AWS credentials configured"
    exit 1
}

# Extract password values
GRAFANA_ADMIN_PASSWORD=$(echo "${SECRETS_JSON}" | jq -r '.default_grafana_admin_password // empty')
DEFAULT_ADMIN_PASSWORD=$(echo "${SECRETS_JSON}" | jq -r '.default_admin_password // empty')
DEFAULT_MEMBER_PASSWORD=$(echo "${SECRETS_JSON}" | jq -r '.default_member_password // empty')

if [ -z "${GRAFANA_ADMIN_PASSWORD}" ] || [ -z "${DEFAULT_ADMIN_PASSWORD}" ] || [ -z "${DEFAULT_MEMBER_PASSWORD}" ]; then
    log_error "One or more required secrets not found"
    exit 1
fi

# Write .env file (escape $ as $$ for docker compose)
GRAFANA_ADMIN_PASSWORD_ESCAPED="${GRAFANA_ADMIN_PASSWORD//\$/\$\$}"
DEFAULT_ADMIN_PASSWORD_ESCAPED="${DEFAULT_ADMIN_PASSWORD//\$/\$\$}"
DEFAULT_MEMBER_PASSWORD_ESCAPED="${DEFAULT_MEMBER_PASSWORD//\$/\$\$}"

cat > "${ENV_FILE}" << EOF
# Generated by scripts/setup-local-env.sh - DO NOT COMMIT
# Regenerate with: ./scripts/setup-local-env.sh

GRAFANA_ADMIN_PASSWORD=${GRAFANA_ADMIN_PASSWORD_ESCAPED}
DEFAULT_ADMIN_PASSWORD=${DEFAULT_ADMIN_PASSWORD_ESCAPED}
DEFAULT_MEMBER_PASSWORD=${DEFAULT_MEMBER_PASSWORD_ESCAPED}
EOF

chmod 600 "${ENV_FILE}"

log_info "Created ${ENV_FILE}"
log_info "You can now run: docker compose up -d"
log_info ""
log_info "To reinitialize Grafana users/teams:"
log_info "  docker compose up grafana-init"